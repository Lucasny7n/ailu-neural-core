export type NeuralNodeType =
  | "core"
  | "system"
  | "kernel"
  | "service"
  | "interface"
  | "hardware"
  | "ai"
  | "memory"
  | "network"
  | "audio"
  | "package"
  | "log"
  | "action";

export type NeuralNodeStatus =
  | "idle"
  | "ready"
  | "thinking"
  | "approval"
  | "running"
  | "success"
  | "warning"
  | "danger"
  | "error";

export interface NeuralNode {
  id: string;
  label: string;
  type: NeuralNodeType;
  status: NeuralNodeStatus;
  description: string;
  depth: number;
  parentId?: string;
  position: [number, number, number];
  diagnosticsKey?: string;
  children?: string[];
}

export interface NeuralConnection {
  id: string;
  from: string;
  to: string;
  status: NeuralNodeStatus;
  label?: string;
  strength: number;
}

