export const nodeById = new Map(neuralNodes.map((item) => [item.id, item]));

export function getNodePath(nodeId: string): NeuralNode[] {
  const path: NeuralNode[] = [];
  let current = nodeById.get(nodeId);
  while (current) {
    path.unshift(current);
    current = current.parentId ? nodeById.get(current.parentId) : undefined;
  }
  return path;
}

export function getChildNodes(nodeId: string): NeuralNode[] {
  const node = nodeById.get(nodeId);
  return node?.children?.map((childId) => nodeById.get(childId)).filter(isNode) ?? [];
}

export function getRelatedNodeIds(nodeId: string): string[] {
  const node = nodeById.get(nodeId);
  const parent = node?.parentId ? [node.parentId] : [];
  return [...new Set([...parent, ...(node?.children ?? [])])];
}

function isNode(value: NeuralNode | undefined): value is NeuralNode {
  return Boolean(value);
}
